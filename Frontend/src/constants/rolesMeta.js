export const ROLE_META_MAP = Object.fromEntries(ROLES_META.map((r) => [r.key, r]));

export const CANONICAL_ROLE_ALIASES = {
  MANAGER: 'BRANCH_MANAGER',
  STAFF: 'FIELD_OFFICER',
  COLLECTOR: 'COLLECTIONS',
  MEMBER: 'MEMBER_PORTAL',
  GUARANTOR: 'GUARANTOR_PORTAL',
};

export function resolveRoleMeta(roleKey) {
  const upper = String(roleKey || 'MEMBER_PORTAL').toUpperCase().replace(/-/g, '_');
  const mapped = CANONICAL_ROLE_ALIASES[upper] || upper;
  return ROLE_META_MAP[mapped] || ROLES_META.find((r) => r.slug === String(roleKey).toLowerCase()) || ROLES_META[0];
}

