function normalizeCapabilityRole(role) {
  const upper = String(role || 'MEMBER_PORTAL').toUpperCase().replace(/-/g, '_').trim();
  return ROLE_CANONICAL_MAP[upper] || upper;
}

function getRoleCapabilities(role) {
  const canonical = normalizeCapabilityRole(role);
  return ROLE_CAPABILITIES_MATRIX[canonical] || ROLE_CAPABILITIES_MATRIX.MEMBER_PORTAL;
}

function hasRoleAction(role, actionKey) {
  const caps = getRoleCapabilities(role);
  return Boolean(caps?.actions?.[actionKey]);
}

