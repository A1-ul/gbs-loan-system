function makeRole(def) {
  return {
    role: def.role,
    title: def.title,
    category: def.category,
    domain: def.domain,
    allowedTabs: def.allowedTabs,
    actions: { ...ALL_FALSE_ACTIONS, ...(def.actions || {}) },
    commands: def.commands || [],
    activityEntityTypes: def.activityEntityTypes || [],
    restrictedNotice: def.restrictedNotice || '',
  };
}

