function hasPermission(role, permission) {
  const normalizedRole = role === 'SUPER_ADMIN' ? ROLES.COMPANY_OWNER : role;
  if (!ACCESS_MATRIX[normalizedRole]) return false;
  return ACCESS_MATRIX[normalizedRole].includes(permission);
}

